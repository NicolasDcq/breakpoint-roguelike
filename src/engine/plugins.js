export const PLUGIN_IDS = Object.keys(PLUGINS);

export const RARITY_LABELS = { common: "Commun", uncommon: "Peu commun", rare: "Rare" };

export function pluginSellPrice(e) {
  return Math.floor(PLUGINS[e].cost / 2);
}

export function effectiveFamilyLevel(L, f2, h2) {
  let v = familyLevel(L, f2);
  if (h2 && v > 1) {
    let m = 1;
    for (let k of FAMILIES) {
      m = Math.max(m, familyLevel(L, k));
    }
    if (v === m) {
      v = 2 * v - 1;
    }
  }
  return v;
}
