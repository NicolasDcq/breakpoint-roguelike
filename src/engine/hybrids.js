const ORDER = Object.keys(MODULES);

// Ordre canonique des deux parents : celui des modules dans MODULES.
export function hybridPair(a, b) {
  return ORDER.indexOf(a) <= ORDER.indexOf(b) ? [a, b] : [b, a];
}

