export function hybridName(a, b) {
  let [first, second] = hybridPair(a, b);
  return HYBRID_NAMES[`${first}+${second}`] ?? `${MODULES[first].name} + ${MODULES[second].name}`;
}

export const isHybrid = (module) => !!module?.fused && !!module.partnerId;

// Familles d'un module : deux pour un hybride de familles différentes.
export function moduleFamilies(module) {
  let first = MODULES[module.defId].family;
  if (!isHybrid(module)) {
    return [first];
  }
  let second = MODULES[module.partnerId].family;
  return second === first ? [first] : [first, second];
}
